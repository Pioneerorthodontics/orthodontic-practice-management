#!/usr/bin/env node
// Builds the two deployable outputs:
//   dist/apps-script/Code.gs + appsscript.json  -> paste into the Apps Script editor (one file, no load-order problems)
//   dist/web/                                   -> upload to GitHub Pages
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dist = path.join(root, 'dist');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
fs.rmSync(dist, { recursive: true, force: true });

const gas = path.join(dist, 'apps-script'); fs.mkdirSync(gas, { recursive: true });
const banner = '/* Ortho Practice Manager — Apps Script backend. Generated by tools/build.js. Do not edit here; edit the source files. */\n';
fs.writeFileSync(path.join(gas, 'Code.gs'), banner + ['shared/ledger.js', 'shared/core.js', 'apps-script/server.js'].map(f => `\n/* ===== ${f} ===== */\n` + read(f)).join('\n'));
fs.copyFileSync(path.join(root, 'apps-script/appsscript.json'), path.join(gas, 'appsscript.json'));

const web = path.join(dist, 'web');
fs.cpSync(path.join(root, 'web'), web, { recursive: true });
fs.copyFileSync(path.join(root, 'shared/ledger.js'), path.join(web, 'ledger.js'));
fs.copyFileSync(path.join(root, 'shared/core.js'), path.join(web, 'core.js'));
// bump the service-worker cache name so phones pick up the new version
const ver = new Date().toISOString().replace(/\D/g, '').slice(0, 12);
const sw = path.join(web, 'sw.js'); fs.writeFileSync(sw, fs.readFileSync(sw, 'utf8').replace('__BUILD__', ver));
console.log('Built dist/apps-script/Code.gs and dist/web (version ' + ver + ')');
